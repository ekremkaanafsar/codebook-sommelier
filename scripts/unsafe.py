"""Unsafe-domain checks shared by merge_records.py, check_links.py and audit_catalog.py.

data/unsafe_domains.txt lists former project domains that now serve unrelated or harmful content. A domain covers
its subdomains. find_unsafe(text) returns the listed domains that appear in a text, as a URL host or as a bare name.

The public export carries no names: data/unsafe_domains.sha256 holds the SHA-256 of each lower-cased domain, one
digest per line. When the .txt file is absent the checks run in hash mode: every host-like token in a text and each of
its parent-domain suffixes is hashed and compared. Regenerate the hash file with
`python scripts/unsafe.py --write-hashes`.
"""
import hashlib
import re
import sys
from urllib.parse import urlparse

from schema import DATA

PATH = DATA / "unsafe_domains.txt"
HASH_PATH = DATA / "unsafe_domains.sha256"

HASH_HEADER = (
    "# SHA-256 of each lower-cased unsafe domain, one hex digest per line, sorted.\n"
    "# A domain also covers its subdomains. The names are not published.\n"
    "# Generated by: python scripts/unsafe.py --write-hashes\n"
)
# host-like token: not preceded by a letter, digit, dot or hyphen; not followed by a letter, digit or hyphen
HOST_RE = re.compile(r"(?<![a-z0-9\-])(?:[a-z0-9\-]+\.)+[a-z]{2,}(?![a-z0-9\-])", re.I)
_HEX = re.compile(r"^[0-9a-f]{64}$")


def sha(domain):
    return hashlib.sha256(domain.strip().lower().encode("utf-8")).hexdigest()


def load(path=None):
    path = path or PATH
    if not path.exists():
        return []
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        d = line.split("#", 1)[0].strip().lower()
        if d:
            out.append(d)
    return out


def load_hashes(path=None):
    path = path or HASH_PATH
    if not path.exists():
        return frozenset()
    out = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        h = line.split("#", 1)[0].strip().lower()
        if _HEX.match(h):
            out.add(h)
    return frozenset(out)


def write_hashes(src=None, dst=None):
    names = load(src or PATH)
    digests = sorted({sha(d) for d in names})
    (dst or HASH_PATH).write_text(HASH_HEADER + "".join(h + "\n" for h in digests), encoding="utf-8", newline="\n")
    return len(digests)


def _suffixes(host):
    labels = host.lower().split(".")
    return [".".join(labels[i:]) for i in range(len(labels) - 1)]


DOMAINS = []
HASHES = frozenset()
_PATTERNS = []


def configure(txt_path=None, hash_path=None):
    """(Re)load the blocklist: names when the .txt exists, otherwise hashes."""
    global DOMAINS, HASHES, _PATTERNS
    DOMAINS = load(txt_path)
    HASHES = frozenset() if DOMAINS or (txt_path or PATH).exists() else load_hashes(hash_path)
    # bare-name match: the domain not preceded by a letter, digit, dot or hyphen (so "x-example.org" or "nexample.org"
    # do not match "example.org") and not followed by a letter, digit or hyphen
    if not DOMAINS and not HASHES:
        sys.stderr.write("warning: no unsafe-domain blocklist (data/unsafe_domains.txt or .sha256): "
                         "unsafe-domain checks are inactive.\n")
    _PATTERNS = [(d, re.compile(r"(?<![a-z0-9.\-])(?:[a-z0-9\-]+\.)*" + re.escape(d) + r"(?![a-z0-9\-])", re.I))
                 for d in DOMAINS]


configure()


def is_unsafe_host(url):
    try:
        host = (urlparse(url if "://" in url else "http://" + url).hostname or "").rstrip(".")
    except ValueError:
        return False
    if HASHES:
        return any(sha(s) in HASHES for s in _suffixes(host))
    return any(host == d or host.endswith("." + d) for d in DOMAINS)


def find_unsafe(text):
    if not text:
        return []
    if HASHES:
        out = []
        for m in HOST_RE.finditer(text):
            tok = m.group(0)
            if any(sha(s) in HASHES for s in _suffixes(tok)) and tok not in out:
                out.append(tok)  # the host as it appears in the scanned text; the listed name stays unknown
        return out
    return [d for d, p in _PATTERNS if p.search(text)]


if __name__ == "__main__":
    if sys.argv[1:] == ["--write-hashes"]:
        if not PATH.exists():
            sys.exit("data/unsafe_domains.txt is missing; nothing to hash")
        print(f"wrote {write_hashes()} digests to {HASH_PATH.name}")
    else:
        sys.exit("usage: python scripts/unsafe.py --write-hashes")
